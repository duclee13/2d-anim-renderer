import { splitIntoMicroBeats, MicroSceneBeat } from "./splitIntoMicroBeats";
import { designSingleSvgAsset } from "./designSingleSvgAsset";
import { directMicroScene } from "./directMicroScene";
import { MasterSceneGraph, SceneGraphScene } from "../../remotion/types/sceneGraph";
import { sanitizeSceneGraph } from "../../remotion/utils/sceneGraphSanitizer";

export interface PipelineProgressCallback {
  (step: 1 | 2 | 3 | 4, message: string, percent: number): void;
}

export interface PipelineOptions {
  rawScript: string;
  modelName?: string;
  apiKey?: string;
  voice?: string;
  onProgress?: PipelineProgressCallback;
}

export interface PipelineExecutionResult {
  success: boolean;
  sceneGraph: MasterSceneGraph;
  beats: MicroSceneBeat[];
  autoGeneratedAssets: string[];
  totalDurationSeconds: number;
}

/**
 * Multi-Prompt Micro-Scene Pipeline Orchestrator (General-Purpose Engine)
 * Tự động xâu chuỗi 3 bước nhỏ độc lập để không bao giờ bị nghẽn hay timeout:
 * - Bước 1: Cắt nhịp kịch bản 3-5s & Đo audio Edge-TTS chính xác
 * - Bước 2: Thiết kế từng vật thể SVG riêng biệt chuẩn 400x400 chạm đáy y=380
 * - Bước 3: Đạo diễn từng khung hình 3-5s với 3 Keyframe States & Semantic Slots
 * - Bước 4: Khóa cứng vật lý & Ghép nối MasterSceneGraph qua sceneGraphSanitizer
 */
export async function runMultiPromptPipeline({
  rawScript,
  modelName = "gemini-3.1-flash-lite",
  apiKey,
  voice = "vi-VN-HoaiMyNeural",
  onProgress,
}: PipelineOptions): Promise<PipelineExecutionResult> {
  const notify = (step: 1 | 2 | 3 | 4, msg: string, pct: number) => {
    if (onProgress) onProgress(step, msg, pct);
    console.log(`[Pipeline Bước ${step}] (${pct}%) ${msg}`);
  };

  // =========================================================================
  // BƯỚC 1: CẮT NHỊP 3-5S & TRÍCH XUẤT TÀI NGUYÊN + TỔNG HỢP EDGE-TTS
  // =========================================================================
  notify(1, "Đang phân rã kịch bản thành các Micro-Scenes 3-5s và tổng hợp giọng đọc Edge-TTS...", 15);
  const beats = await splitIntoMicroBeats(rawScript, modelName, apiKey, voice);

  // =========================================================================
  // BƯỚC 2: THIẾT KẾ TỪNG OBJECT RIÊNG BIỆT (1 PROMPT / 1 OBJECT)
  // =========================================================================
  notify(2, "Kiểm tra kho tài nguyên và thiết kế vector SVG chuẩn 400x400 cho các vật thể...", 40);

  const allRequiredProps = Array.from(
    new Set(beats.flatMap((b) => b.requiredProps))
  );

  const autoGeneratedAssets: string[] = [];

  for (const propId of allRequiredProps) {
    try {
      const designResult = await designSingleSvgAsset(propId, modelName, apiKey);
      if (!designResult.cached) {
        autoGeneratedAssets.push(designResult.propId);
      }
    } catch (err: any) {
      console.warn(`[Pipeline Bước 2] Bỏ qua lỗi thiết kế prop '${propId}':`, err.message);
    }
  }

  // =========================================================================
  // BƯỚC 3: ĐẠO DIỄN TỪNG KHUNG 3-5S (1 PROMPT / 1 CẢNH)
  // =========================================================================
  notify(3, `Đang đạo diễn chi tiết ${beats.length} Micro-Scenes (3 Keyframe States & Semantic Slots)...`, 70);

  const directedScenes: SceneGraphScene[] = [];

  for (let i = 0; i < beats.length; i++) {
    const beat = beats[i];
    notify(3, `Đang đạo diễn cảnh ${i + 1}/${beats.length}: "${beat.name}"...`, 70 + Math.round((i / beats.length) * 20));
    const scene = await directMicroScene(beat, modelName, apiKey);
    directedScenes.push(scene);
  }

  // =========================================================================
  // BƯỚC 4: GHÉP CẢNH VÀ KHÓA CỨNG HÌNH HỌC QUA SCENE GRAPH SANITIZER
  // =========================================================================
  notify(4, "Khóa kiểm duyệt hình học, thời lượng động tuyệt đối và ghép nối Master Scene Graph...", 95);

  let currentStart = 0;
  const assembledScenes: SceneGraphScene[] = directedScenes.map((s, idx) => {
    const sStart = currentStart;
    const sDur = s.durationInFrames;
    currentStart = sStart + sDur;

    // Đồng bộ startFrame nối tiếp nhau tuyệt đối
    const updatedSubs = (s.subtitles || []).map((sub, sIdx) => ({
      ...sub,
      startFrame: sStart + 5,
      endFrame: sStart + sDur - 5,
    }));

    const updatedBubbles = (s.speechBubbles || []).map((b, bIdx) => ({
      ...b,
      startFrame: sStart + 10,
      endFrame: sStart + sDur - 10,
    }));

    return {
      ...s,
      id: `scene_${idx + 1}`,
      startFrame: sStart,
      durationInFrames: sDur,
      subtitles: updatedSubs,
      speechBubbles: updatedBubbles,
    };
  });

  const rawMasterGraph: MasterSceneGraph = {
    version: "3.2.0",
    title: beats[0]?.name || "Micro-Scene 2D Explainer Video",
    width: 2560,
    height: 1440,
    fps: 60,
    totalDurationInFrames: currentStart,
    scenes: assembledScenes,
  };

  // Khóa cứng vật lý, clipping bàn ghế, clipping vật chứa, camera bounds qua Sanitizer
  const sanitizedGraph = sanitizeSceneGraph(rawMasterGraph, rawScript);

  notify(4, "Toàn bộ Micro-Scene Pipeline đã hoàn tất thành công 100%!", 100);

  return {
    success: true,
    sceneGraph: sanitizedGraph,
    beats,
    autoGeneratedAssets,
    totalDurationSeconds: currentStart / 60,
  };
}
